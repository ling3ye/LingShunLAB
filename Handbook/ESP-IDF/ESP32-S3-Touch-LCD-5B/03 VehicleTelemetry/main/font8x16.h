/**
 * Tiny 8x16 monospace bitmap font (header-only).
 *
 * Each glyph is 16 bytes, one per scan line. Within a byte, bit 7 (0x80) is
 * the leftmost pixel of the 8-wide cell, bit 0 (0x01) the rightmost.
 *
 * Only the glyphs needed for "Hello World!" are included; unsupported
 * characters render as a blank (space) cell. Add glyphs here to extend.
 *
 * NOTE: glyph arrays are prefixed GLYPH_ to avoid colliding with the
 *       FONT_W / FONT_H dimension macros below.
 */
#pragma once

#include <stdint.h>

#define FONT_W 8
#define FONT_H 16

static const uint8_t GLYPH_BLANK[16] = {
    0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
};
static const uint8_t GLYPH_EXCL[16] = {     /* '!' */
    0x00,0x00,0x18,0x18,0x18,0x18,0x18,0x18,0x00,0x00,0x18,0x18,0x00,0x00,0x00,0x00,
};
static const uint8_t GLYPH_CAP_H[16] = {    /* 'H' */
    0x00,0x00,0x42,0x42,0x42,0x42,0x42,0x7E,0x42,0x42,0x42,0x42,0x42,0x00,0x00,0x00,
};
static const uint8_t GLYPH_LOW_E[16] = {    /* 'e' */
    0x00,0x00,0x00,0x00,0x00,0x3C,0x42,0x7E,0x40,0x40,0x42,0x3C,0x00,0x00,0x00,0x00,
};
static const uint8_t GLYPH_LOW_L[16] = {    /* 'l' */
    0x00,0x00,0x20,0x20,0x20,0x20,0x20,0x20,0x20,0x20,0x20,0x20,0x70,0x00,0x00,0x00,
};
static const uint8_t GLYPH_LOW_O[16] = {    /* 'o' */
    0x00,0x00,0x00,0x00,0x00,0x3C,0x42,0x42,0x42,0x42,0x42,0x3C,0x00,0x00,0x00,0x00,
};
static const uint8_t GLYPH_CAP_W[16] = {    /* 'W' */
    0x00,0x00,0x42,0x42,0x42,0x42,0x66,0x66,0x5A,0x5A,0x5A,0x18,0x00,0x00,0x00,0x00,
};
static const uint8_t GLYPH_LOW_R[16] = {    /* 'r' */
    0x00,0x00,0x00,0x00,0x00,0x70,0x48,0x40,0x40,0x40,0x40,0x40,0x40,0x00,0x00,0x00,
};
static const uint8_t GLYPH_LOW_D[16] = {    /* 'd' */
    0x00,0x00,0x04,0x04,0x04,0x04,0x3C,0x44,0x44,0x44,0x44,0x3C,0x00,0x00,0x00,0x00,
};

/* Return the 16-byte glyph for ch, or a blank cell if unsupported. */
static inline const uint8_t *font8x16_glyph(unsigned char ch)
{
    switch (ch) {
        case ' ':  return GLYPH_BLANK;
        case '!':  return GLYPH_EXCL;
        case 'H':  return GLYPH_CAP_H;
        case 'e':  return GLYPH_LOW_E;
        case 'l':  return GLYPH_LOW_L;
        case 'o':  return GLYPH_LOW_O;
        case 'W':  return GLYPH_CAP_W;
        case 'r':  return GLYPH_LOW_R;
        case 'd':  return GLYPH_LOW_D;
        default:   return GLYPH_BLANK;
    }
}
